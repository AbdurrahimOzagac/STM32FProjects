static void I2C_Bus_Recovery(GPIO_TypeDef *port, uint16_t scl_pin, uint16_t sda_pin)
{
    GPIO_InitTypeDef GPIO_InitStruct = {0};

    // SCL ve SDA'yı manuel open-drain GPIO çıkışı yap
    GPIO_InitStruct.Mode  = GPIO_MODE_OUTPUT_OD;
    GPIO_InitStruct.Pull  = GPIO_PULLUP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;

    GPIO_InitStruct.Pin = scl_pin;
    HAL_GPIO_Init(port, &GPIO_InitStruct);
    GPIO_InitStruct.Pin = sda_pin;
    HAL_GPIO_Init(port, &GPIO_InitStruct);

    HAL_GPIO_WritePin(port, sda_pin, GPIO_PIN_SET);
    HAL_GPIO_WritePin(port, scl_pin, GPIO_PIN_SET);

    // SDA hâlâ LOW ise, slave'i serbest bırakmak için 9 clock darbesi gönder
    for (int i = 0; i < 9; i++)
    {
        if (HAL_GPIO_ReadPin(port, sda_pin) == GPIO_PIN_SET)
            break;

        HAL_GPIO_WritePin(port, scl_pin, GPIO_PIN_RESET);
        HAL_Delay(1);
        HAL_GPIO_WritePin(port, scl_pin, GPIO_PIN_SET);
        HAL_Delay(1);
    }

    // Manuel STOP condition: SDA LOW iken SCL HIGH, sonra SDA HIGH
    HAL_GPIO_WritePin(port, sda_pin, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(port, scl_pin, GPIO_PIN_SET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(port, sda_pin, GPIO_PIN_SET);
    HAL_Delay(1);
}


